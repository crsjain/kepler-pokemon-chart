#!/usr/bin/env node
/**
 * Builds emoji_data.js (the Admin › Activities icon search data) from
 * emojibase-data's English dataset. Run it when bumping the data version:
 *
 *   curl -sLo /tmp/emoji.json https://cdn.jsdelivr.net/npm/emojibase-data@16.0.3/en/data.json
 *   node tools/build_emoji_data.js /tmp/emoji.json
 *
 * Kept: Emoji <= 14.0 (the iPadOS 15.4 floor set by 🪥, so search never offers
 * icons that old tablets draw as blank boxes); no skin-tone variants (they are
 * nested in `skins`, which we ignore) and no components (group 2: hair / skin
 * swatches, regional indicator letters). Each row is [emoji, name, keywords].
 * Spec: docs/prd_activity_icon_picker.md §10.3.
 */
const fs = require('fs');
const path = require('path');

const MAX_VERSION = 14;
const COMPONENT_GROUP = 2;
const SOURCE = 'emojibase-data 16.0.3 en/data.json';

// Kid-activity words the standard keywords miss, so chart words find icons.
const EXTRA_KEYWORDS = {
  '💮': 'chinese mandarin', '🀄': 'chinese mandarin', '🉐': 'chinese mandarin', '🧧': 'chinese mandarin',
  '📚': 'homework', '✏️': 'homework', '📝': 'homework',
  '🎹': 'practice', '🎻': 'practice',
  '🧹': 'chores', '🧺': 'chores', '🧼': 'chores',
  '🪥': 'brush teeth'
};

const input = process.argv[2];
if (!input) {
  console.error('Usage: node tools/build_emoji_data.js <path to emojibase en/data.json>');
  process.exit(1);
}
const norm = s => s.replace(/\uFE0F/g, '');
const extra = Object.fromEntries(Object.entries(EXTRA_KEYWORDS).map(([k, v]) => [norm(k), v]));
const data = JSON.parse(fs.readFileSync(input, 'utf8'));
const rows = data
  .filter(e => e.version <= MAX_VERSION && e.group !== COMPONENT_GROUP)
  // Lone regional indicator letters (🇦) are filed under Flags but are flag halves, not icons.
  .filter(e => !/^\p{Regional_Indicator}$/u.test(e.emoji))
  .map(e => {
    const keywords = [...(e.tags || []), extra[norm(e.emoji)] || ''].join(' ').trim();
    return [e.emoji, e.label, keywords];
  });

const header = `// GENERATED by tools/build_emoji_data.js from ${SOURCE}. Do not edit by hand.
// Emoji data © emojibase contributors, MIT licence (https://github.com/milesj/emojibase).
// ${rows.length} emoji (Emoji <= ${MAX_VERSION}.0, no skin tones, components or lone regional indicators). Rows: [emoji, name, keywords].
// Loaded lazily by admin.js (icon picker search); see docs/prd_activity_icon_picker.md §10.3.
`;
const body = `export const EMOJI_DATA = [\n${rows.map(r => JSON.stringify(r)).join(',\n')}\n];\n`;
const out = path.join(__dirname, '..', 'emoji_data.js');
fs.writeFileSync(out, header + body);
console.log(`Wrote ${out}: ${rows.length} emoji, ${Buffer.byteLength(header + body)} bytes`);
